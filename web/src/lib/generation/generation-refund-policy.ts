/**
 * 生成任务的积分退款政策（纯逻辑：不连库、不触网、无依赖，可直接单测）。
 *
 * 规则（2026-09-19 起，老板定的）：任务一旦开跑，预扣的积分就不再退回，
 * **不论最后有没有成品**——上游明确报错、超时被清扫、用户自己取消，一律照收。
 *
 * 为什么敢这么定：
 *   1) 上游按「一次尝试」计费。请求发出去钱就花掉了，上游不会因为我们这边判失败而退给我们；
 *      旧规则（浏览器一断就退款）等于把上游成本全揽在平台身上：钱付了、额度还退回去。
 *   2) 9-18 起成品由服务端自己归档，任务就算判了失败/取消，图往往还在我们手里
 *      （记录页可取、可按保留期下载）——「没生成」不再等于「用户什么都没拿到」。
 *   3) 上游 99% 的调用其实是成功的，「失败」多半出在我们与浏览器之间的这一段，
 *      拿这段链路的抖动去免费送图，账就对不上了。
 *
 * 退款代码保留不删（credit-ledger 的幂等退款 + 各结算点的调用），政策可能再变，
 * 改下面这一个开关就够，不必重新长一遍那些幂等与对账的结构。
 *
 * 只管生成任务的积分扣退；订单（支付通道）的退款不走这里。
 */

/** 生成失败/取消是否退还预扣积分。2026-09-19 起为 false（不退）。 */
export const GENERATION_REFUNDS_ENABLED = false;

/**
 * 这次结算要不要把预扣的积分退回去。
 * 成功从来就不退（预扣即实收）；失败/取消看上面的开关。
 */
export function shouldRefundGeneration(status: "succeeded" | "failed" | "cancelled"): boolean {
    if (status === "succeeded") return false;
    return GENERATION_REFUNDS_ENABLED;
}
